package setup

import (
	"bytes"
	"fmt"
	"strings"
	"text/template"
)

// Options are the admin's choices.
type Options struct {
	Mode        string // manual | ldap
	Ports       []Port // ports Switchboard takes over
	DefaultCert string // HAProxy bundle for clients without SNI; empty = build from the infra certificate
	UpstreamIP  string
	ExtraCA     string // optional CA trusted for customer certificates (private CA)
}

// Paths written by setup.
const (
	ConfigPath     = "/etc/switchboard/config.yaml"
	HAProxyPath    = "/etc/haproxy/haproxy.cfg"
	DefaultPEM     = "/etc/haproxy/default.pem"
	CarbonioCAPath = "/etc/haproxy/carbonio-ca.pem"
	CertDir        = "/etc/haproxy/certs"
	SystemCABundle = "/etc/ssl/certs/ca-certificates.crt"
)

// BackendCA is the CA file used to verify Carbonio's certificate.
func (e *Env) BackendCA() string {
	if e.InfraPublic {
		return SystemCABundle
	}
	return CarbonioCAPath
}

type tmplData struct {
	Env        *Env
	Opts       Options
	Implicit   []Port
	StartTLS   []Port
	BackendCA  string
	UpstreamCA string
}

func data(e *Env, o Options) tmplData {
	d := tmplData{Env: e, Opts: o, BackendCA: e.BackendCA()}
	if !e.InfraPublic {
		d.UpstreamCA = CarbonioCAPath
	}
	for _, p := range o.Ports {
		if p.Implicit {
			d.Implicit = append(d.Implicit, p)
		} else {
			d.StartTLS = append(d.StartTLS, p)
		}
	}
	return d
}

var funcs = template.FuncMap{
	"limits": func(p Port) string {
		if p.Protocol == "smtp" {
			return "sc0_conn_rate gt 30 } || { sc0_conn_cur gt 20"
		}
		return "sc0_conn_rate gt 60 } || { sc0_conn_cur gt 50"
	},
	"frontend": func(p Port) string {
		return map[string]string{"imap": "imaps", "pop3": "pop3s", "smtp": "smtps"}[p.Protocol]
	},
}

var haproxyTmpl = template.Must(template.New("haproxy").Funcs(funcs).Parse(`# Generated by switchboard setup. Implicit TLS ports in front of Carbonio.
global
    log /dev/log local0
    user haproxy
    group haproxy
    daemon
    setcap cap_net_admin,cap_net_raw
    maxconn 20000
    ssl-default-bind-options ssl-min-ver TLSv1.2
    ssl-default-server-options ssl-min-ver TLSv1.2

defaults
    mode tcp
    log global
    option tcplog
    timeout connect 5s
    timeout client 30m
    timeout server 30m
{{- range .Implicit}}

frontend {{frontend .}}
    bind :{{.Local}} ssl crt {{$.Opts.DefaultCert}} crt /etc/haproxy/certs/
    stick-table type ip size 100k expire 10m store conn_rate(60s),conn_cur
    tcp-request connection track-sc0 src
    tcp-request content set-log-level silent if { src 127.0.0.1 }
    tcp-request connection reject if { {{limits .}} }
    default_backend carbonio_{{frontend .}}
{{- end}}
{{range .Implicit}}
backend carbonio_{{frontend .}}
    server carbonio {{$.Opts.UpstreamIP}}:{{.Public}} source 0.0.0.0 usesrc clientip ssl verify required ca-file {{$.BackendCA}} verifyhost {{$.Env.VerifyName}}
{{end -}}
`))

