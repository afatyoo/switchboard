// RenderHAProxy returns haproxy.cfg, or nil when no implicit TLS port is selected.
func RenderHAProxy(e *Env, o Options) ([]byte, error) {
	d := data(e, o)
	if len(d.Implicit) == 0 {
		return nil, nil
	}
	var b bytes.Buffer
	err := haproxyTmpl.Execute(&b, d)
	return b.Bytes(), err
}

// RenderConfig returns /etc/switchboard/config.yaml.
func RenderConfig(e *Env, o Options) ([]byte, error) {
	var b bytes.Buffer
	err := configTmpl.Execute(&b, data(e, o))
	return b.Bytes(), err
}

// ValidateOptions checks the choices against what was detected.
func ValidateOptions(e *Env, o Options) error {
	var errs []string
	switch o.Mode {
	case "manual":
	case "ldap":
		if e.LDAPISocket == "" {
			errs = append(errs, "mode ldap needs the Carbonio ldapi socket on this node (/run/carbonio/run/ldapi)")
		}
	default:
		errs = append(errs, fmt.Sprintf("unknown mode %q", o.Mode))
	}
	if len(o.Ports) == 0 {
		errs = append(errs, "no ports selected")
	}
	if o.DefaultCert == "" {
		errs = append(errs, "no default certificate")
	}
	if o.UpstreamIP == "" {
		errs = append(errs, "no upstream address")
	}
	if len(errs) > 0 {
		return fmt.Errorf("%s", strings.Join(errs, "; "))
	}
	return nil
}

// SelectPorts filters detected ports by a list like "993,995,587".
// An empty list keeps every detected port.
func SelectPorts(detected []Port, list string) ([]Port, error) {
	if strings.TrimSpace(list) == "" {
		return detected, nil
	}
	want := map[string]bool{}
	for _, f := range strings.Split(list, ",") {
		want[strings.TrimSpace(f)] = true
	}
	var out []Port
	for _, p := range AllPorts {
		k := fmt.Sprint(p.Public)
		if !want[k] {
			continue
		}
		delete(want, k)
		found := false
		for _, d := range detected {
			if d.Public == p.Public {
				found = true
			}
		}
		if !found {
			return nil, fmt.Errorf("port %d: Carbonio is not listening on it", p.Public)
		}
		out = append(out, p)
	}
	for k := range want {
		return nil, fmt.Errorf("unknown port %s (supported: 993, 995, 465, 587, 143, 110)", k)
	}
	return out, nil
}
